/**
 * Generates a video of a model walking in the outfit using Veo.
 */
export const generateRunwayVideo = async (imageBase64: string): Promise<string> => {
  // 1. Mandatory API Key Selection for Veo
  if (window.aistudio && window.aistudio.hasSelectedApiKey) {
    const hasKey = await window.aistudio.hasSelectedApiKey();
    if (!hasKey) {
      await window.aistudio.openSelectKey();
      // We assume the user selected a key successfully and proceed.
    }
  }

  // 2. Initialize AI with the (potentially new) key
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY || '' });

  try {
    // 3. Start Video Generation
    let operation = await ai.models.generateVideos({
      model: VIDEO_MODEL_NAME,
      prompt: 'A professional fashion model wearing this exact outfit walking down a fashion runway. Front view, confident walk. Cinematic lighting, 4k, slow motion. High fashion.',
      image: {
        imageBytes: imageBase64,
        mimeType: 'image/png',
      },
      config: {
        numberOfVideos: 1,
        resolution: '720p',
        aspectRatio: '9:16'
      }
    });

    // 4. Poll for completion
    while (!operation.done) {
      await new Promise(resolve => setTimeout(resolve, 5000)); // Wait 5 seconds
      operation = await ai.operations.getVideosOperation({ operation: operation });
    }

    // 5. Retrieve Video
    const videoUri = operation.response?.generatedVideos?.[0]?.video?.uri;
    if (!videoUri) {
      throw new Error("Video generation completed but no URI returned.");
    }

    // 6. Fetch the video blob using the API key
    const response = await fetch(`${videoUri}&key=${process.env.API_KEY}`);
    if (!response.ok) {
      throw new Error(`Failed to download video: ${response.statusText}`);
    }
    const blob = await response.blob();
    
    // 7. Create a local object URL
    return URL.createObjectURL(blob);

  } catch (error) {
    console.error("Error generating runway video:", error);
    throw error;
  }
};
import { GoogleGenAI, GenerateContentResponse } from "@google/genai";
import { OutfitStyle } from "../types";

const MODEL_NAME = 'gemini-2.5-flash-image';
const VIDEO_MODEL_NAME = 'veo-3.1-fast-generate-preview';

/**
 * Encodes a File object to a base64 string.
 */
export const fileToGenerativePart = async (file: File): Promise<string> => {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => {
      const base64String = reader.result as string;
      // Remove the data URL prefix (e.g., "data:image/jpeg;base64,")
      const base64Data = base64String.split(',')[1];
      resolve(base64Data);
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
};

/**
 * Extracts the image data from a Gemini response.
 * It looks for an inlineData part first.
 */
const extractImageFromResponse = (response: GenerateContentResponse): string | null => {
  if (!response.candidates || response.candidates.length === 0) return null;
  
  const content = response.candidates[0].content;
  if (!content || !content.parts) return null;

  // Iterate through parts to find the image
  for (const part of content.parts) {
    if (part.inlineData && part.inlineData.data) {
      return `data:${part.inlineData.mimeType || 'image/png'};base64,${part.inlineData.data}`;
    }
  }
  return null;
};

/**
 * Generates an outfit based on the uploaded item and a specific style.
 */
export const generateOutfit = async (imageBase64: string, style: OutfitStyle): Promise<string> => {
  // Always create a new instance to ensure we use the latest key if it changed
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY || '' });

  const prompt = `
    Act as a professional high-end fashion stylist.
    I have provided an image of a clothing item.
    Create a complete, stylish ${style} outfit that features this item as the centerpiece.
    Generate a high-quality, photorealistic "flat-lay" style image of the entire outfit arranged neatly on a neutral, clean background.
    Ensure the lighting is soft and professional.
    The output must be an image.
  `;

  try {
    const response = await ai.models.generateContent({
      model: MODEL_NAME,
      contents: {
        parts: [
          {
            inlineData: {
              mimeType: 'image/jpeg', // Assuming jpeg for simplicity, but could be png
              data: imageBase64
            }
          },
          { text: prompt }
        ]
      }
    });

    const imageUrl = extractImageFromResponse(response);
    if (!imageUrl) {
      throw new Error("No image generated by the model.");
    }
    return imageUrl;
  } catch (error) {
    console.error("Error generating outfit:", error);
    throw error;
  }
};

